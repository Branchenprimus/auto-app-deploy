#!/usr/bin/env python3
"""Render Homepage's local icon registry and ConfigMap from checked-in PNGs.

No downloads, credentials, or live application access are needed to regenerate.
"""
import base64
from pathlib import Path
import re
import yaml

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'platform/homepage-icons'
MANIFEST = ROOT / 'platform/homepage.yaml'
REGISTRY = ROOT / 'chart/single-container-webapp/files/homepage-icons.yaml'


def main():
    sources = yaml.safe_load((ASSETS/'sources.yaml').read_text())
    files = {p.name: p.read_bytes() for p in sorted(ASSETS.glob('*.png'))}
    for name, raw in files.items():
        if not raw.startswith(b'\x89PNG\r\n\x1a\n'):
            raise ValueError('Not a PNG: '+name)
    if sum(map(len, files.values())) > 800_000:
        raise ValueError('Icon ConfigMap is too large')
    for group in ('apps', 'services'):
        for key, filename in sources[group].items():
            if filename not in files or Path(filename).name != filename:
                raise ValueError('Missing or invalid local icon for '+key)
    if 'app-default.png' not in files:
        raise ValueError('Missing default icon for future apps')

    registry = {name: '/icons/'+filename for name, filename in sorted(sources['apps'].items())}
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY.write_text('# Generated by scripts/render-homepage-icons.py\n'+yaml.safe_dump(registry, sort_keys=True))
    text = MANIFEST.read_text()
    sections = text.split('\n---\n')
    updated_icons = False
    updated_services = set()
    for index, section in enumerate(sections):
        document = yaml.safe_load(section)
        if document.get('kind') != 'ConfigMap':
            continue
        name = document['metadata']['name']
        if name == 'homepage-icons':
            document.pop('data', None)
            document['binaryData'] = {name: base64.b64encode(raw).decode() for name, raw in files.items()}
            sections[index] = yaml.safe_dump(document, sort_keys=False).rstrip()
            updated_icons = True
        elif name == 'homepage':
            inside_services = False
            current_service = None
            result = []
            for line in section.splitlines():
                if line == '  services.yaml: |':
                    inside_services = True
                elif inside_services and re.match(r'^  [a-zA-Z][^ ]*:', line):
                    inside_services = False
                if inside_services:
                    match = re.match(r'^        - (.+):\s*$', line)
                    if match:
                        current_service = match.group(1)
                    if re.match(r'^            icon:', line):
                        filename = sources['services'].get(current_service)
                        if filename is None:
                            # Repository discovery may add new cards independently.
                            # Preserve a verified existing local icon in that case.
                            existing = line.split('icon:', 1)[1].strip()
                            if existing.startswith('/icons/') and existing.removeprefix('/icons/') in files:
                                filename = existing.removeprefix('/icons/')
                            else:
                                raise ValueError('No icon configured for service '+str(current_service))
                        line = '            icon: /icons/'+filename
                        updated_services.add(current_service)
                result.append(line)
            sections[index] = '\n'.join(result)
    if not updated_icons:
        raise ValueError('homepage-icons ConfigMap not found')
    MANIFEST.write_text('\n---\n'.join(sections).rstrip()+'\n')
    print('Rendered '+str(len(files))+' PNG assets, '+str(len(registry))+' app icons, '+str(len(updated_services))+' manual service icons.')


if __name__ == '__main__':
    main()
